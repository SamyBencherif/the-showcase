#!/usr/bin/env node
// Writes projects.js: the list of files in projects/ that the date selector reads.
// A web page can't list a folder by itself, so rerun this after adding files.
//
// Usage: node build-projects.js [--watch]
'use strict';

const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, 'projects');
const out = path.join(__dirname, 'projects.js');

function build() {
  const files = fs.existsSync(dir)
    ? fs.readdirSync(dir, { withFileTypes: true })
      .filter((d) => d.isFile() && !d.name.startsWith('.'))
      .map((d) => d.name)
      .sort()
    : [];
  const js = '// Generated by build-projects.js. Do not edit.\n' +
    `window.PROJECT_FILES = ${JSON.stringify(files, null, 2)};\n`;
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== js) {
    fs.writeFileSync(out, js);
    console.log(`projects.js: ${files.length} file(s)`);
  }
}

build();

if (process.argv.includes('--watch')) {
  let timer;
  fs.watch(dir, () => {
    clearTimeout(timer);
    timer = setTimeout(build, 100);
  });
  console.log('Watching projects/ for changes...');
}
